#!/usr/bin/env python3
"""Cancellation-preserving origin residual certificate on an enlarged disk.

Uses the fresh complete origin field coefficient enclosures generated by
origin_certificate.py, and independently reconstructs the low residual
polynomial from the same exact source.  No historical norm evidence is used.
"""
import argparse
from collections import defaultdict
from hashlib import sha256
import json
import math
from pathlib import Path
from types import SimpleNamespace
import sys
import time
from flint import arb, fmpq as Q, fmpq_poly, ctx
sys.set_int_max_str_digits(0)


def enc(x):
    assert x.is_finite()
    return [str(x.lower().fmpq()), str(x.upper().fmpq())]


def ball(pair):
    l,u=map(Q,pair)
    return arb((l+u)/2)+arb(0,arb((u-l)/2).upper())


def polys(field, floor=10):
    S=32
    out={}
    for (kind,n,p),v in field.items():
        if p>floor:continue
        assert n<=S
        if (p,kind) not in out:out[p,kind]=[Q(0)]*(2*S+1)
        out[p,kind][S+n]+=v/2
        out[p,kind][S-n]+=v/2 if kind=='c' else -v/2
    return {k:fmpq_poly(v) for k,v in out.items()}


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--ipm-root',type=Path,default=Path('/mnt/d/Changhe_D/PDE_exploring/Changhe/IPM'))
    ap.add_argument('--field-data',type=Path,default=Path('/tmp/residual_recertification/origin_certificate.json'))
    ap.add_argument('--radius',default='1/1000')
    ap.add_argument('--output',type=Path,default=Path('/tmp/residual_recertification/origin_large_certificate.json'))
    args=ap.parse_args();started=time.monotonic();ctx.prec=384
    sys.path.insert(0,str(args.ipm_root/'combined3/IPM.artifacts/coercivity_residual'))
    from fields013 import Evaluator,C,SOURCE_HASHES,rational_arb
    from asymptotics013 import Expansion,hdiff
    field_input_bytes=args.field_data.read_bytes()
    data=json.loads(field_input_bytes)
    assert data['status']=='VALIDATED_ORIGIN_DISK_PRIMARY_ENCLOSURE'
    assert data['source_sha256']==SOURCE_HASHES and Q(data['fixed_c_exact'])==C
    assert data['degree']==16
    r=arb(Q(args.radius));z=r*r/arb(Q(data['analytic_factor_cauchy_radius_exact']))
    assert r>0 and z<arb(1)/4
    P={};T={};field_raw={}
    for key,row in data['field_uniform_enclosures'].items():
        name,i,j=key.split(',');i=int(i);j=int(j)
        finite={Q(t['power_exact']):ball(t['coefficient_abs_sum_enclosure_exact']).upper()
                for t in row['finite_terms']}
        # The saved tail coefficient already includes a factor >1.  Retain
        # that factor and multiply by the new geometric denominator, which
        # is conservative for the enlarged disk.
        tail={Q(t['power_exact']):ball(t['coefficient_enclosure_exact']).upper()/(1-2*z)
              for t in row['tail_terms']}
        P[name,i,j]=finite
        T[name,i,j]=sum((v*r**rational_arb(p) for p,v in tail.items()),arb(0)).upper()
        field_raw[key]={'finite_coefficients':[{'power_exact':str(p),'abs_coefficient_upper_exact':str(v.fmpq())}for p,v in sorted(finite.items())],
                        'new_tail_sum_enclosure_exact':enc(T[name,i,j])}
    def value(row):return sum((v*r**rational_arb(p)for p,v in row.items()),arb(0)).upper()
    PV={k:value(v)for k,v in P.items()}
    e=Evaluator(384)
    a=Expansion(SimpleNamespace(groups=[g for g in e.groups if g[1]<=13]),'origin',degree=6)
    fields={k:a.field(*k)for k in [('rho',0,0),('rho',1,0),('rho',0,1),('u1',0,0),('u2',0,0)]}
    f=defaultdict(Q)
    for (kind,n,p),v in fields['rho',0,0].items():
        if p<=10:f[kind,n,p]+=(C*p-1)*v
    for uk,gk in [(('u1',0,0),('rho',1,0)),(('u2',0,0),('rho',0,1))]:
        for (p,k),A in polys(fields[uk]).items():
            for (q,l),B in polys(fields[gk]).items():
                if p+q>10:continue
                assert k!=l
                AB=A*B
                for n in range(1,65):
                    v=2*AB[64+n]
                    if v:f['s',n,p+q]+=v
    f={k:v for k,v in f.items()if v}
    assert f and all(p>=3 and p>=n and int(p-n)%2==0 for (_,n,p)in f)
    print('retained residual',len(f),'elapsed',time.monotonic()-started,flush=True)
    omitted=defaultdict(lambda:arb(0))
    for p,v in P['rho',0,0].items():
        if p>10:omitted[p]+=abs(arb(C*p-1))*v
    for uk,gk in [(('u1',0,0),('rho',1,0)),(('u2',0,0),('rho',0,1))]:
        for p,v in P[uk].items():
            for q,w in P[gk].items():
                if p+q>10:omitted[p+q]+=v*w
    residual_raw={};B={}
    for total in range(4):
        for i in range(total+1):
            j=total-i;ff=f
            for axis in 'x'*i+'y'*j:
                grouped=defaultdict(dict);nxt=defaultdict(Q)
                for (kind,n,p),v in ff.items():grouped[p][kind,n]=v
                for p,mm in grouped.items():
                    for (kind,n),v in hdiff(mm,p,axis).items():nxt[kind,n,p-1]+=v
                ff={k:v for k,v in nxt.items()if v}
            retained=sum((arb(abs(v))*r**rational_arb(p)for (_,_,p),v in ff.items()),arb(0))
            # A regular homogeneous polynomial of degree p stays regular
            # under differentiation, and its angular Fourier l1 derivative
            # bound is at most p at the first step, p-1 at the next, etc.
            omitted_derivative=sum((v*math.prod(int(p)-k for k in range(total))*r**rational_arb(p-total)
                                     for p,v in omitted.items()),arb(0))
            analytic=arb(C)*r*(T['rho',i+1,j]+T['rho',i,j+1])+abs(arb(C*total-1))*T['rho',i,j]
            for ii in range(i+1):
                for jj in range(j+1):
                    mult=math.comb(i,ii)*math.comb(j,jj)
                    for name,dx,dy in [('u1',1,0),('u2',0,1)]:
                        uk=name,ii,jj;gk='rho',i-ii+dx,j-jj+dy
                        analytic+=mult*(PV[uk]*T[gk]+T[uk]*PV[gk]+T[uk]*T[gk])
            bound=(retained+omitted_derivative+analytic).upper();B[i,j]=bound
            residual_raw[f'{i},{j}']={'retained_polynomial_abs_enclosure_exact':enc(retained),
                                     'omitted_finite_abs_enclosure_exact':enc(omitted_derivative),
                                     'analytic_remainder_abs_enclosure_exact':enc(analytic),
                                     'uniform_abs_upper_exact':str(bound.fmpq())}
    area=arb.pi()*r*r;l2=area*B[0,0]**2
    tensors=[]
    for total in range(4):
        s=arb(0)
        for i in range(total+1):
            j=total-i;v=B[i,j];gx=2*r*v;gy=2*r*v
            if i:gx+=2*i*B[i-1,j]
            if j:gy+=2*j*B[i,j-1]
            s+=math.comb(total,i)*(v*v+gx*gx+gy*gy)
        tensors.append((area*s).upper())
    E2=(tensors[0].sqrt()+(2*tensors[2]).sqrt())**2
    E3=E2+(tensors[1].sqrt()+(2*tensors[3]).sqrt())**2
    out={'status':'VALIDATED_ENLARGED_ORIGIN_DISK_PRIMARY_ENCLOSURE',
         'source_sha256':SOURCE_HASHES,'fixed_c_exact':str(C),'radius_exact':args.radius,
         'field_data_sha256':sha256(field_input_bytes).hexdigest(),
         'field_data_code_sha256':data['code_sha256'],
         'retained_residual_power_cutoff':10,'low_potential_harmonic_cutoff':13,'low_expansion_degree':6,
         'retained_residual_coefficients':[{'kind':k,'harmonic':n,'power_exact':str(p),'coefficient_enclosure_exact':enc(arb(v))}for(k,n,p),v in sorted(f.items())],
         'omitted_finite_residual_coefficients':[{'power_exact':str(p),'absolute_coefficient_enclosure_exact':enc(v)}for p,v in sorted(omitted.items())],
         'field_derivative_data':field_raw,'residual_derivative_enclosures':residual_raw,
         'F_L2_energy_upper_exact':str(l2.upper().fmpq()),'F_L2_energy_enclosure_exact':enc(l2),
         'G_ordered_tensor_energy_uppers_exact':[str(v.fmpq())for v in tensors],
         'G_E2_definition':'integral_disk |(1-Delta)G|^2',
         'G_E3_definition':'integral_disk (|(1-Delta)G|^2+|gradient(1-Delta)G|^2)',
         'G_E2_energy_upper_exact':str(E2.upper().fmpq()),'G_E3_energy_upper_exact':str(E3.upper().fmpq()),
         'G_E2_triangle_enclosure_exact':enc(E2),'G_E3_triangle_enclosure_exact':enc(E3),
         'precision_bits':ctx.prec,'code_sha256':sha256(Path(__file__).read_bytes()).hexdigest(),
         'elapsed_seconds':time.monotonic()-started}
    args.output.write_text(json.dumps(out,indent=2)+'\n')
    print('L2',l2.str(30),'E2',E2.str(30),'E3',E3.str(30),'seconds',time.monotonic()-started,flush=True)


if __name__=='__main__':main()
