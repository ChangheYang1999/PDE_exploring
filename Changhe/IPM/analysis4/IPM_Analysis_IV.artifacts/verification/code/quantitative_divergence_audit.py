"""Exact common-denominator audit for the quantitative prime-center theorem."""
from pathlib import Path
from fractions import Fraction
from math import isqrt,lcm
from hashlib import sha256
from datetime import datetime,timezone
import json,sys,time
sys.set_int_max_str_digits(0)


def prime(p):
    return p>=2 and all(p%d for d in range(2,isqrt(p)+1))


def denominator_bound(p,a,B,Q):
    D=Q**p*(4*a)**(p-1)
    for n in range(2,p+1):D *= (n-1)**(p//n)
    count=0
    for i in range(1,p):
        for j in range(1,B*i//2+1):
            vp=(2*j+2)*p-i*a;vm=(2*j-2)*p+i*a
            assert vp and vm
            assert max(abs(vp),abs(vm)) <= (B+3)*i*p
            D*=abs(vp*vm)**(p//i);count+=2*(p//i)
    S=sum(i*(p//i) for i in range(1,p))
    assert count==B*S
    # A purely integer finite upper bound for the asymptotic height estimate.
    finite=Q**p*(4*p)**p*(p-1)**sum(p//n for n in range(2,p+1))*((B+3)*p*p)**(B*S)
    assert D<=finite
    return D,S,finite


def check(row,profile,B,Q,source):
    d=Fraction(row['delta']);a,p=d.numerator,d.denominator
    assert prime(p) and a%2==0 and 4<=a<p and row['n0']==p
    D,S,finite=denominator_bound(p,a,B,Q)
    density={k:Fraction(v) for k,v in row['density_at_resonance'].items()}
    for k,v in density.items():assert D%v.denominator==0,(source,d,k)
    kappa=Fraction(row['kappa_exact']);assert kappa and D%kappa.denominator==0
    assert abs(kappa.numerator)*D>=kappa.denominator
    return dict(profile=profile,delta=str(d),p=p,a=a,B=B,leading_common_denominator_bit_length=Q.bit_length(),
                checked_density_coefficients=len(density),all_denominators_divide_D=True,
                common_denominator_bit_length=D.bit_length(),max_actual_denominator_bit_length=max(v.denominator.bit_length() for v in density.values()),
                stream_factor_multiplicity=B*S,finite_height_upper_bound_verified=True,
                finite_upper_bound_bit_length=finite.bit_length(),nonzero_kappa_lower_bound_verified=True,
                source=source)


def main():
    start=time.monotonic();cases=[];hashes={};seen=set()
    for path in sorted(Path('research/24_rational_scan/verification').glob('sin1_*.json')):
        if path.stem.endswith('summary'):continue
        raw=path.read_bytes();row=json.loads(raw);d=Fraction(row['delta'])
        if not(prime(d.denominator) and d.numerator%2==0 and d.numerator>=4):continue
        cases.append(check(row,'sin1',2,1,str(path)));seen.add(str(d));hashes[str(path)]=sha256(raw).hexdigest()
    path=Path('research/31_prime_denominator_obstruction/verification/modular_checks.json');raw=path.read_bytes();hashes[str(path)]=sha256(raw).hexdigest()
    for row in json.loads(raw)['direct_cartesian_checks']:
        if row['delta'] in seen:continue
        cases.append(check(row,'sin1',2,1,str(path)));seen.add(row['delta'])
    path=Path('research/02_candidate007/data/leading_exact.json');raw=path.read_bytes();hashes[str(path)]=sha256(raw).hexdigest()
    leading=json.loads(raw)['density'];Q=lcm(*(Fraction(v).denominator for v in leading.values()));B=max(map(int,leading))+1
    for name in ['cand007_6_13.json','cand007_8_17.json']:
        path=Path('research/24_rational_scan/verification')/name;raw=path.read_bytes();hashes[str(path)]=sha256(raw).hexdigest()
        cases.append(check(json.loads(raw),'candidate007',B,Q,str(path)))
    # A mixed rational profile independently generated now, with a nontrivial Q.
    sys.dont_write_bytecode=True
    from rational_scan_audit import compute
    initial={1:'2/3',3:'-1/5',5:'1/11'};Q=lcm(*(Fraction(v).denominator for v in initial.values()))
    for p,a in [(7,4),(7,6),(11,4),(11,8)]:
        row=compute(Fraction(a,p),initial,p)
        cases.append(check(row,'rational_three_mode',6,Q,'generated by independent Cartesian recurrence'))
    target=Path('research/46_quantitative_divergence/verification/checks.json')
    out=dict(checked_at_utc=datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
             code_sha256=sha256(Path(__file__).read_bytes()).hexdigest(),
             proof_sha256=sha256(Path('research/46_quantitative_divergence/PROOF.md').read_bytes()).hexdigest(),
             source_hashes=hashes,cases=cases,case_count=len(cases),
             total_coefficients_checked=sum(r['checked_density_coefficients'] for r in cases),
             actual_elapsed_s=time.monotonic()-start,
             scope='Exact finite divisibility checks corroborate the tree denominator bound; the all-order theorem requires its separate proof and review.')
    target.write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps({k:out[k] for k in ['checked_at_utc','case_count','total_coefficients_checked','actual_elapsed_s']}),flush=True)

if __name__=='__main__':main()
