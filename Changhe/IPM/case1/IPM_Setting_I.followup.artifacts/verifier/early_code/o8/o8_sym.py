# sympy checks of the q=0 closed forms used in fred22 03 section 3 (reference bounds)
import sympy as sp
u, A, t = sp.symbols('u A t', positive=True)
w0 = -A*u*(1-u**2)/(1+u**2)
g0 = u**2/(1+u**2)
print('w0pp - 4Au(3-u^2)/(1+u^2)^3 =', sp.simplify(sp.diff(w0, u, 2) - 4*A*u*(3-u**2)/(1+u**2)**3))
w3 = sp.factor(sp.diff(w0, u, 3)); print('w0ppp =', w3)
print('k0 - 2/(u(1+u^2)) =', sp.simplify(sp.diff(g0, u)/g0 - 2/(u*(1+u**2))), '; k0 =(w0p-A)/w0 check:', sp.simplify((sp.diff(w0,u)-A)/w0 - sp.diff(g0,u)/g0))
print("k0' =", sp.factor(sp.diff(2/(u*(1+u**2)), u)))
a0 = sp.factor(-w0/(1-u)); print('a0 =', a0, "; a0'/A =", sp.factor(sp.diff(a0, u)/A))
z0 = sp.factor(-w0/(A*u)); print('z0 =', z0, '; D0 =', sp.factor(u*sp.diff(z0, u)), '; J0 =', sp.factor(-sp.diff(w0, u, 2)/(A*u)))
print('E0 + log(1-u^2) =', sp.simplify(sp.log(g0/(u**2*z0)) + sp.log(1-u**2)))
f = (1+6*t+t**2)/(1+t)**4; print("d/dt (1+6t+t^2)/(1+t)^4 numerator:", sp.factor(sp.numer(sp.together(sp.diff(f, t)))))
W = sp.simplify((a0/A)**(sp.Symbol('b')-2)*g0**(1-sp.Symbol('b'))); print('weight =', W)
print('|w0ppp| <= 12A(1+6u^2+u^4)/(1+u^2)^4 :', sp.factor(w3 - 12*A*(-1+6*u**2-u**4)/(1+u**2)**4))
# Q(1) at the reference
e = sp.Symbol('e')
Q = sp.simplify((sp.diff(g0, u) - e*sp.diff(w0, u, 2))/(2*g0**3))
print('Q(1) =', sp.simplify(Q.subs(u, 1)), '; Q =', sp.expand(sp.simplify(Q)))
