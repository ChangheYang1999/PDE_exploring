"""Own exact energy controls: direct polynomial disk/circle integrals and radial energy.

No fitting-lane code, network, server, or symbolic PDE solver is used.
The proof is research/151_renormalized_energy_audit/PROOF.md.
"""
from pathlib import Path
from datetime import datetime, timezone
import hashlib, json, sys, time
import sympy as S
from fractions import Fraction

root=Path(sys.argv[1]); root.mkdir(exist_ok=True)
start=time.monotonic(); rows=[]
x,y,R,r,t,lam=S.symbols('x y R r t lam', positive=True)
pi=S.pi

def angle_moment(a,b):
    if a%2 or b%2:return S.Integer(0)
    i,j=a//2,b//2
    return 2*pi*S.factorial(2*i)*S.factorial(2*j)/(4**(i+j)*S.factorial(i)*S.factorial(j)*S.factorial(i+j))

def integ(p,disk):
    out=0
    for (a,b),c in S.Poly(S.expand(p),x,y).terms():
        val=c*angle_moment(a,b)*R**(a+b)
        if disk:val*=R**2/S.Integer(a+b+2)
        out+=val
    return S.expand(out)

def check(name,expr,**info):
    result=S.factor(expr)
    assert result==0,(name,result)
    rows.append({'name':name,'verdict':'PASS',**info})

# Manufactured fields include nonzero thermal residuals, so the sign of -int y t
# is checked independently of any exact-transport simplification.
psis=[x*(x*x+y*y)+2*x*y, x*y+x**3/S.Integer(7)+x*y**3/S.Integer(3),
      x*(1+x*x+y+y*y+x*x*y)/S.Integer(5)-x/S.Integer(5)]
thetas=[x*x*(1+y+y*y+x*x),x*x*(2-y+x*x*y),x*x*(1+2*y**3)]
for beta in [S.Rational(9,4),S.Rational(7,2),S.Integer(6)]:
    c=1+beta/2; q=4/beta
    cases=list(zip(psis,thetas))+[(c*x*y-q*x**3/6,x*x)]
    for j,(p,th) in enumerate(cases):
        px,py=S.diff(p,x),S.diff(p,y)
        om=-S.diff(p,x,2)-S.diff(p,y,2)
        wx,wy=beta*x-py,beta*y+px
        ff=wx*S.diff(om,x)+wy*S.diff(om,y)+om-S.diff(th,x)
        tt=wx*S.diff(th,x)+wy*S.diff(th,y)-(beta-2)*th
        en=(px*px+py*py)/2+y*th
        radial=x*px+y*py; wdot=wx*x+wy*y
        boundary=p*om*wdot+beta*(radial**2-R**2*(px*px+py*py)/2)+(2*beta-1)*p*radial-x*p*th+y*th*wdot
        check(f'disk_identity_beta{beta}_field{j}',integ(p*ff+(4*beta-2)*en+y*tt,True)-integ(boundary,False))
        if j==3:
            check(f'exact_polynomial_transport_beta{beta}',tt)
            check(f'exact_polynomial_vorticity_beta{beta}',ff)

p=x*(x*x+y*y)+2*x*y;om=-8*x
v_dot_x=-S.diff(p,y)*x+S.diff(p,x)*y
check('nonzero_cubic_flux',integ(p*om*v_dot_x,False)-4*pi*R**6)

# Harmonic cross term: use arbitrary real C,D and direct circle coefficients.
C,D,beta=S.symbols('C D beta',real=True)
cc,ss=S.symbols('cc ss',real=True)
pr=C*cc-D*R**-2*cc;pa=-C*R*ss-D*R**-1*ss;p=C*R*cc+D*R**-1*cc
b=S.expand(beta*(R**2*pr**2-pa**2)/2+(2*beta-1)*R*p*pr)
constant=S.expand(b).coeff(R,0)
check('harmonic_CD_integrand',constant+beta*C*D*(cc**2+ss**2))
check('harmonic_CD_integral',constant.subs(cc**2,1).subs(ss**2,1)*pi+2*pi*beta*C*D)

# Candidate collision arithmetic. This checks the stated formal set, not the PDE.
for n in range(1,8):
    for m in range(2*n+1,6*n+1):
        z=Fraction(m,n)
        possible=any((z*d).denominator==1 for d in range(1,5))
        expected=z.denominator<=4
        assert possible==expected,(z,possible)
        if expected:
            ell,nn=z.numerator,4-z.denominator
            assert Fraction(4)-Fraction(ell)/z-nn==0
        rows.append({'name':f'collision_{m}_{n}','verdict':'PASS','reduced_beta':str(z),'candidate':possible})

# Finite-part radial energy computed independently from its angular energy density.
# These algebraic controls use polynomial interiors matched continuously in stream;
# they are not smooth profile examples. Smooth sign examples are proved by approximation.
for beta in [S.Rational(9,4),S.Rational(7,2),S.Integer(6)]:
    s=1/beta
    for j,f in enumerate([S.Rational(1,10000),1+lam*(1-r*r)**2,1+lam*r*r*(1-r*r)**3]):
        I=S.integrate(t**3*f.subs(r,t),(t,0,r)); h=-S.integrate(I/r**3,r)
        h=S.expand(h-h.subs(r,0))
        A=1/((3-s)*(1-s))
        c=(1/(1-s)-S.integrate(r*f,(r,0,1)))/2
        d=(S.integrate(r**3*f,(r,0,1))-1/(3-s))/2
        outer_terms=[(2-s,-A),(S.Integer(1),c),(S.Integer(-1),d)]
        # E_inner/(pi/2), then subtract the constant generated by integrating
        # each direct radial energy power from1 toR.
        inner=S.integrate(((h+r*S.diff(h,r))**2+h*h)*r,(r,0,1))
        fp=inner
        for e,a in outer_terms:
            for ep,ap in outer_terms:
                exponent=e+ep
                assert exponent!=0 or S.simplify(a*ap*(e*ep+1))==0
                if exponent!=0:fp-=a*ap*(e*ep+1)/exponent
        formula=2*c*d+S.integrate(I*I/r**3,(r,0,1))-1/((3-s)**2*(4-2*s))-4*d/((3-s)*(1-s))+2*d*d
        check(f'radial_fp_beta{beta}_poly{j}',fp-formula)
        if j==0:
            assert formula>0
            rows.append({'name':f'positive_smallcore_control_beta{beta}','verdict':'PASS','bracket_exact':str(formula)})
        else:
            bump=S.diff(f,lam)
            double=-S.integrate(r*bump*S.integrate(t*(r*r-t*t)*bump.subs(r,t),(t,0,r)),(r,0,1))/2
            check(f'negative_quadratic_factor_beta{beta}_poly{j}',S.expand(formula).coeff(lam,2)-double)
            assert double<0
            negative=formula.subs(lam,1000)
            assert negative<0
            rows.append({'name':f'negative_largecore_control_beta{beta}_poly{j}','verdict':'PASS','quadratic_exact':str(double),'lambda':1000})

# New D=0 controls after section7a's complete smooth concentration argument.
# Exact piecewise cumulative-mass controls test the limiting bounds used there;
# they are not advertised as smooth profiles.
for beta in [S.Rational(9,4),S.Rational(7,2),S.Integer(6)]:
    s=1/beta; mass=1/(3-s); threshold=mass**2/(4-2*s)
    for delta in [S.Rational(1,4),S.Rational(1,10),S.Rational(1,40)]:
        inner_cumulative=mass*(r/delta)**4
        qinner=S.integrate(inner_cumulative**2/r**3,(r,0,delta))+S.integrate(mass**2/r**3,(r,delta,1))
        check(f'D0_inner_concentration_formula_{beta}_{delta}',qinner-mass**2*(S.Rational(2,3)/delta**2-S.Rational(1,2)))
        assert qinner>threshold
        rows.append({'name':f'D0_positive_sign_{beta}_{delta}','verdict':'PASS','bracket_exact':str(qinner-threshold)})
    delta=S.Rational(1,40)
    qouter_bound=mass**2*delta/(1-delta)**3
    assert qouter_bound<threshold
    rows.append({'name':f'D0_negative_outer_bound_{beta}','verdict':'PASS','upper_bracket_exact':str(qouter_bound-threshold)})
    c=S.symbols('c',real=True)
    h=-r**(1-s)/((3-s)*(1-s))+c
    computed=-((s+1)*h+r*S.diff(h,r))*r**(-s-1)
    target=2*r**(-2*s)/((3-s)*(1-s))-(s+1)*c*r**(-s-1)
    check(f'D0_nonprofile_exterior_residual_{beta}',computed-target)

out={'utc':datetime.now(timezone.utc).isoformat(),'elapsed_seconds':time.monotonic()-start,'status':'COMPLETE','count':len(rows),'rows':rows,'limitations':'Exact algebra controls and collision bookkeeping only. No proof of a B2 profile, no positivity sign theorem with nonzero temperature jet, no interval or convergence certification. No NUM code executed/imported.','code_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
(root/'results.json').write_text(json.dumps(out,indent=2)+'\n')
print('PASS',len(rows),'elapsed',out['elapsed_seconds'],flush=True)
